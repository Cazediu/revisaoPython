# VERIFICAR VALORES AUSENTES
# =========================

print("Valores ausentes antes do tratamento:\n")

print(df[["Classificação de Usuários", "Idade Recomendada"]].isnull().sum())

# =========================
# TRATAMENTO DA COLUNA
# CLASSIFICAÇÃO DE USUÁRIOS
# =========================

# Escolha:
# Utilizar a MÉDIA, pois é uma variável contínua
# e normalmente representa notas com distribuição numérica.

media_classificacao = df["Classificação de Usuários"].mean()

df["Classificação de Usuários"] = df["Classificação de Usuários"].fillna(media_classificacao)

print("\nMédia utilizada em 'Classificação de Usuários':")
print(media_classificacao)

# =========================
# TRATAMENTO DA COLUNA
# IDADE RECOMENDADA
# =========================

# Escolha:
# Utilizar a MEDIANA, pois a coluna pode possuir
# valores extremos e a mediana sofre menos influência
# de outliers.

mediana_idade = df["Idade Recomendada"].median()

df["Idade Recomendada"] = df["Idade Recomendada"].fillna(mediana_idade)

print("\nMediana utilizada em 'Idade Recomendada':")
print(mediana_idade)

