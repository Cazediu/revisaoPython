import pandas as pd
from sklearn.preprocessing import LabelEncoder

# =========================
# CARREGAR DATASET
# =========================

df = pd.read_csv("game_dataset.csv")

# =========================
# REMOVER COLUNA IRRELEVANTE
# =========================

df = df.drop(columns=["Nome do Jogo"])

# =========================
# IDENTIFICAR COLUNAS CATEGÓRICAS
# =========================

colunas_categoricas = df.select_dtypes(include=["object"]).columns

print("Colunas categóricas:\n")
print(colunas_categoricas)

# =========================
# LABEL ENCODING
# =========================

# O Label Encoding é utilizado em variáveis binárias,
# pois existem apenas duas categorias.
# Assim, cada categoria pode ser representada
# por 0 e 1 sem criar colunas extras.

label = LabelEncoder()

for coluna in colunas_categoricas:

    quantidade_categorias = df[coluna].nunique()

    if quantidade_categorias == 2:

        df[coluna] = label.fit_transform(df[coluna])

        print(f"\nLabel Encoding aplicado na coluna: {coluna}")

# =========================
# ONE-HOT ENCODING
# =========================

# O One-Hot Encoding é utilizado em variáveis
# com mais de duas categorias.
# Isso evita que o modelo interprete uma ordem
# numérica inexistente entre categorias.

colunas_onehot = []

for coluna in colunas_categoricas:

    if df[coluna].nunique() > 2:

        colunas_onehot.append(coluna)

# Aplicando One-Hot Encoding

df = pd.get_dummies(df, columns=colunas_onehot)

# =========================
# RESULTADO FINAL
# =========================

print("\nDataset após conversão:\n")

print(df.head())

print("\nNovas dimensões do dataframe:\n")

print(df.shape)

print("\nTipos de dados finais:\n")

print(df.dtypes)

