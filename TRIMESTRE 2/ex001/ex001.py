import matplotlib.pyplot as plt



df = pd.read_csv("game_dataset.csv")

# Remover coluna sem relevância
df = df.drop(columns=["Nome do Jogo"])

# Remover duplicatas
df = df.drop_duplicates()




colunas_numericas = df.select_dtypes(include=["int64", "float64"]).columns

print("Colunas numéricas:")
print(colunas_numericas)


for coluna in colunas_numericas:

    plt.figure(figsize=(6,4))

    plt.boxplot(df[coluna].dropna())

    plt.title(f"Boxplot antes - {coluna}")

    plt.ylabel(coluna)

    plt.show()



df_tratado = df.copy()

for coluna in colunas_numericas:

    # Quartis
    Q1 = df_tratado[coluna].quantile(0.25)
    Q3 = df_tratado[coluna].quantile(0.75)

    # Intervalo interquartil
    IQR = Q3 - Q1

    # Limites
    limite_inferior = Q1 - 1.5 * IQR
    limite_superior = Q3 + 1.5 * IQR

    # Filtrar dados sem outliers
    df_tratado = df_tratado[
        (df_tratado[coluna] >= limite_inferior) &
        (df_tratado[coluna] <= limite_superior)
    ]


for coluna in colunas_numericas:

    plt.figure(figsize=(6,4))

    plt.boxplot(df_tratado[coluna].dropna())

    plt.title(f"Boxplot depois - {coluna}")

    plt.ylabel(coluna)

    plt.show()

# =========================
# TAMANHO FINAL
# =========================

print("\nTamanho original:")
print(df.shape)

print("\nTamanho após remoção de outliers:")
print(df_tratado.shape)

